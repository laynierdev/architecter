"use client";

import { useProject } from "@/state/ProjectContext";

/**
 * Tells the user which AI produced what they are looking at. AI output is never presented as
 * authoritative, and mock or fallback answers are always labelled as such.
 */
export function AiNotice({ what }: { what: string }) {
  const { aiMode } = useProject();
  if (!aiMode.known) return null;

  if (aiMode.provider === "gemini") {
    return (
      <div className="alert alert-info py-2 fs-xs d-flex gap-2" role="note">
        <i className="bi bi-stars" aria-hidden="true" />
        <div>
          Generated by <strong>Gemini</strong>
          {aiMode.model ? ` (${aiMode.model})` : ""}. AI can make mistakes: review the {what} before you rely on it.
        </div>
      </div>
    );
  }

  return (
    <div className="alert alert-warning py-2 fs-xs d-flex gap-2" role="note">
      <i className="bi bi-robot" aria-hidden="true" />
      <div>
        {aiMode.fallback ? (
          <>
            <strong>Mock answer.</strong> {aiMode.reason ?? "The AI provider was unavailable."} This {what} comes from the built-in rule-based mock, not a language model.
          </>
        ) : (
          <>
            <strong>Mock AI.</strong> This {what} is composed from your project data by fixed rules, not by a language model. Configure a Gemini API key on the server to use real AI.
          </>
        )}{" "}
        Review it before you rely on it.
      </div>
    </div>
  );
}
